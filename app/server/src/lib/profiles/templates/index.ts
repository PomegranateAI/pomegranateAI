/**
 * The Tier A/B fields a template author actually authors (spec-data-agents-
 * and-subfolder-wiki.md §5.1/§5.2) — everything on `ContextProfile` EXCEPT
 * the Tier C fields (`review_kinds`, `query_scopes`, `feedback_dimensions`,
 * `flag_semantics`), which are never shown in the editor and generated by
 * `deriveTemplateProfile` below, and the Tier D fields (`consequence`,
 * `anchor`), which are never asked about at all — dead in the current
 * runtime, so a draft simply can't declare them through this type.
 */
export type DraftTemplateProfile = Omit<
  ContextProfileT,
  'review_kinds' | 'query_scopes' | 'feedback_dimensions' | 'flag_semantics'
> & {
  kinds: Array<Omit<NodeKindDef, 'consequence' | 'anchor'>>;
};

/**
 * Fills in the Tier C fields a draft never carries — the point of Tier C
 * (§5.1: "not shown anywhere, generated silently at save"). This is the
 * ACTUAL mechanism that makes an essentials-only editor produce a valid,
 * `validateProfileSemantics`-passing profile: without it, the schema's own
 * `.min(1)` constraints on review_kinds/query_scopes/feedback_dimensions
 * would force every caller to supply them anyway, defeating the whole
 * point of not showing them.
 *
 * - `review_kinds` = every declared kind key.
 * - `query_scopes` = one scope per kind, plus the mandatory `'all'` scope
 *   the validator itself requires.
 * - `feedback_dimensions` / `flag_semantics` = a short, generic set
 *   paraphrased from the kind descriptions already written — a real,
 *   working default, not a placeholder; a template author who wants to
 *   hand-tune either can still do so by supplying them explicitly (the
 *   spread below never overwrites a value the draft already set).
 */
export function deriveTemplateProfile(draft: DraftTemplateProfile): ContextProfileT {
  const kindKeys = draft.kinds.map((k) => k.key);
  const firstKindLabel = draft.kinds[0]?.label_plural ?? 'entries';
  const derived: ContextProfileT = {
    ...draft,
    review_kinds: kindKeys,
    query_scopes: [
      { key: 'all', label: 'Everything', kind_keys: 'all' },
      ...draft.kinds.map((k) => ({ key: k.key, label: k.label_plural, kind_keys: [k.key] })),
    ],
    feedback_dimensions: [
      { key: 'accuracy', label: 'Accuracy', description: `whether the draft matches what this folder's ${firstKindLabel} currently say` },
      { key: 'coverage', label: 'Coverage', description: `whether the draft accounts for the ${firstKindLabel} this folder tracks` },
    ],
    flag_semantics: {
      red: `states something a currently-active entry here directly contradicts`,
      yellow: `refers to something not tracked here, or a status this template does not support`,
      green: `consistent with what this folder currently holds (default)`,
    },
  };
  return { ...derived, ...draft } as ContextProfileT; // draft's own values (if it set any) win
}

/**
 * The standard data-agent template catalog — optional, attachable templates a
 * subfolder can layer on top of the notes baseline, never a workspace's only
 * profile. Each file is a PLACEHOLDER: its structure (ids, shapes, kind keys,
 * attrs, edges, source channels) is real, and its prose is a minimal working
 * default meant to be replaced. Shapes covered: `items` (appointment,
 * people_list, policy_book, brand_voice), `slots` (project_status, strategy),
 * `log` (todo_list, decision_log, evidence_log, goals_metrics, spec_sheet,
 * user_insight). `brand_voice` uses a distinct display name from the built-in
 * `brand_voice` workspace profile.
 */
export const STANDARD_DATA_AGENT_TEMPLATES: Record<string, ContextProfileT> = {
  todo_list: todoListTemplate,
  project_status: projectStatusTemplate,
  appointment: appointmentTemplate,
  decision_log: decisionLogTemplate,
  evidence_log: evidenceLogTemplate,
  goals_metrics: goalsMetricsTemplate,
  people_list: peopleListTemplate,
  policy_book: policyBookTemplate,
  spec_sheet: specSheetTemplate,
  strategy: strategyTemplate,
  user_insight: userInsightTemplate,
  brand_voice: brandVoiceTemplate,
};

export function listStandardDataAgentTemplates(): ContextProfileT[] {
  return Object.values(STANDARD_DATA_AGENT_TEMPLATES);
}

export function getStandardDataAgentTemplate(id: string): ContextProfileT | undefined {
  return STANDARD_DATA_AGENT_TEMPLATES[id];
}
